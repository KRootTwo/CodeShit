a=int(input("Enter a number: "))
b=int(input("Enter a number: "))
op=input("Enter the operator(+,-,/,*): ")

if op=="+":
    print("a+b=",a+b)
    print(a,op,b,"=",a+b)
elif op=="-":
    print("a-b=",a-b)
    print(a,op,b,"=",a-b)
else:
    print("Invalid input")

    
    
    
    
    
    
    
    
    